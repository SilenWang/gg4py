def build():
    p = (
        ggplot(to_column_table(DATA), aes(x="mpg", y="disp"))
        + geom_point()
        + guides(x="axis", y="axis", **{"x.sec": "axis", "y.sec": "axis"})
        + facet_grid(rows="cyl", cols="vs", axes="all", axis_labels="margins")
        + labs(title="facet_grid with omitted inner axis labels")
        + theme_test()
    )
    return {"plot": p, "size": [10, 8]}
